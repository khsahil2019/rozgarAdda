class Employer {
  final int id;
  final String companyName;
  final String email;
  final String phone;
  final String contactPerson;
  final String address;
  final String token;

  const Employer({
    required this.id,
    required this.companyName,
    required this.email,
    required this.phone,
    required this.contactPerson,
    required this.address,
    required this.token,
  });
}
